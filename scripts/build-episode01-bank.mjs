// Parses scripts/source/episode01-question-bank.md into src/data/episodes/episode01Bank.js.
// Listening (LS01–LS10) is kept in listeningBank.js because it also drives the MeloTTS clips; it is only cross-checked here.
import fs from 'node:fs';
import { listeningBank } from '../src/data/episodes/listeningBank.js';

const source = fs.readFileSync(new URL('./source/episode01-question-bank.md', import.meta.url), 'utf8').replace(/\r\n/g, '\n');
const clean = text => text.replace(/\\\n/g, ' ').replace(/\\$/gm, '').replace(/\*\*/g, '').replace(/\\_/g, '_').replace(/\s+/g, ' ').trim();
const field = (block, label) => {
  const match = block.match(new RegExp(`\\*\\*${label}:\\*\\*([\\s\\S]*?)(?=\\n\\s*\\n|\\n\\*\\*|\\n---|$)`));
  return match ? clean(match[1]) : '';
};

const blocks = source.split(/^### /m).slice(1).map(raw => {
  const [head, ...rest] = raw.split('\n');
  const [id, level, topic] = head.split('—').map(part => part.trim());
  return { id, level, topic, body: rest.join('\n').split(/\n---/)[0] };
});

const byPrefix = prefix => blocks.filter(block => block.id.startsWith(prefix));

const quiz = byPrefix('QZ').map(({ id, level, topic, body }) => ({
  id, level, topic,
  prompt: field(body, 'Question'),
  answer: field(body, 'Correct answer'),
  accepted: field(body, 'Accepted').split(';').map(value => value.trim()).filter(Boolean)
}));

const reading = byPrefix('RD').map(({ id, level, topic, body }) => {
  const options = [...body.matchAll(/^([A-D])\.\s*(.+?)\\?$/gm)].map(match => clean(match[2]));
  const letter = field(body, 'Correct');
  return {
    id, level, topic,
    passage: field(body, 'Passage'),
    prompt: field(body, 'Question'),
    options,
    answer: 'ABCD'.indexOf(letter)
  };
});

const speaking = byPrefix('SP').map(({ id, level, topic, body }) => ({ id, level, topic, prompt: clean(body) }));

const writing = byPrefix('WR').map(({ id, level, topic, body }) => {
  const task = field(body, 'Task');
  const range = task.match(/(\d+)[–-](\d+) words/);
  return {
    id, level, topic,
    prompt: task,
    minWords: Number(range[1]),
    maxWords: Number(range[2]),
    requirement: field(body, 'Controlled requirement'),
    control: field(body, 'Control')
  };
});

const listeningDoc = byPrefix('LS').map(({ id, body }) => ({
  id,
  audioText: field(body, 'Audio').replace(/[“”]/g, ''),
  accepted: field(body, 'Accepted').split('/').map(value => value.trim())
}));

const problems = [];
const expect = (condition, message) => { if (!condition) problems.push(message); };
expect(quiz.length === 10 && reading.length === 10 && speaking.length === 10 && writing.length === 10 && listeningDoc.length === 10, 'each skill needs 10 items');
reading.forEach(item => expect(item.options.length === 4 && item.answer >= 0 && item.passage && item.prompt, `${item.id} incomplete`));
quiz.forEach(item => expect(item.prompt && item.accepted.length, `${item.id} incomplete`));
writing.forEach(item => expect(item.minWords && item.maxWords > item.minWords, `${item.id} word range`));
for (const doc of listeningDoc) {
  const have = listeningBank.find(entry => entry.id === doc.id);
  expect(have, `${doc.id} missing from listeningBank`);
  if (!have) continue;
  expect(have.audioText.replace(/\s+/g, ' ') === doc.audioText.replace(/’/g, "'"), `${doc.id} transcript differs from the bank document`);
  const normalise = value => value.toLowerCase();
  expect(doc.accepted.every(value => have.accepted.map(normalise).includes(normalise(value))), `${doc.id} accepted answers differ from the bank document`);
}
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }

const out = `// Generated by scripts/build-episode01-bank.mjs from scripts/source/episode01-question-bank.md. Do not edit by hand.
// The Quiz lane now draws from the central bank (src/data/quizBank.js); the old Europe quiz is archived in src/data/legacy/europeQuizBank.js.
export const readingBank = ${JSON.stringify(reading, null, 2)};

export const speakingBank = ${JSON.stringify(speaking, null, 2)};

export const writingBank = ${JSON.stringify(writing, null, 2)};
`;
fs.writeFileSync(new URL('../src/data/episodes/episode01Bank.js', import.meta.url), out);
fs.mkdirSync(new URL('../src/data/legacy/', import.meta.url), { recursive: true });
fs.writeFileSync(new URL('../src/data/legacy/europeQuizBank.js', import.meta.url), `// Archived Episode 01 Europe quiz (replaced by the central quiz bank). Not used by the game.\nexport const europeQuizBank = ${JSON.stringify(quiz, null, 2)};\n`);
console.log(`Wrote bank: ${reading.length} reading, ${speaking.length} speaking, ${writing.length} writing (${quiz.length} Europe quiz archived); listening cross-check passed.`);
