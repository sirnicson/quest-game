// Fetches one openly licensed Wikimedia Commons image per quiz question into assets/quiz/ and writes assets/quiz/CREDITS.md.
// Usage: node scripts/fetch-quiz-images.mjs [QZ01 QZ02 ...]   (no ids = all). Existing files are kept unless listed explicitly.
import fs from 'node:fs';
import path from 'node:path';

const outDir = new URL('../assets/quiz/', import.meta.url);
fs.mkdirSync(outDir, { recursive: true });
const creditsFile = new URL('./credits.json', outDir);
const credits = fs.existsSync(creditsFile) ? JSON.parse(fs.readFileSync(creditsFile, 'utf8')) : {};

// Atmosphere only: queries avoid showing the answer itself.
const queries = {
  QZ01: 'white dove flying sky',
  QZ02: 'vintage biplane early aviation',
  QZ03: 'dawn sky bright star horizon',
  QZ04: 'human skeleton anatomy bones',
  QZ05: 'night sky moon silhouette',
  QZ06: 'solar system planets illustration',
  QZ07: 'chalkboard mathematics classroom',
  QZ08: 'african savanna landscape',
  QZ09: 'rocky seashore tide pool',
  QZ10: 'sunrise over horizon',
  QZ11: 'fresh fruit market stall',
  QZ12: 'World War I trench soldiers',
  QZ13: 'world flags united nations',
  QZ14: 'smartphone apps social media',
  QZ15: 'world map continents globe',
  QZ16: 'human body anatomy diagram',
  QZ17: 'stadium crowd floodlights night',
  QZ18: 'vineyard grapes harvest',
  QZ19: 'tropical wetland swamp',
  QZ20: 'boreal forest taiga',
  QZ21: 'ancient Roman ruins',
  QZ22: 'World War II bomber aircraft',
  QZ23: 'Mongolian steppe horseback',
  QZ24: 'American Revolution painting',
  QZ25: 'desert caravan camels',
  QZ26: 'crowded city aerial view',
  QZ27: 'Elizabethan theatre stage',
  QZ28: 'open ocean waves',
  QZ29: 'spider web morning dew',
  QZ30: 'Scandinavian furniture interior'
};

const wanted = process.argv.slice(2);
const ids = wanted.length ? wanted : Object.keys(queries);
const headers = { 'User-Agent': 'QUEST-game/5.0 (https://quest.sirnicson.com; educational game) node' };
const okLicense = /^(cc0|cc[ -]by(?!.*nc)|cc[ -]by-sa(?!.*nc)|public domain|pd)/i;
const strip = html => String(html ?? '').replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();

async function search(query) {
  const url = 'https://commons.wikimedia.org/w/api.php?' + new URLSearchParams({
    action: 'query', format: 'json', generator: 'search', gsrnamespace: '6', gsrlimit: '25',
    gsrsearch: `${query} filetype:bitmap`, prop: 'imageinfo', iiprop: 'url|size|mime|extmetadata', iiurlwidth: '800'
  });
  const res = await fetch(url, { headers });
  const data = await res.json();
  return Object.values(data.query?.pages ?? {}).sort((a, b) => a.index - b.index);
}

for (const id of ids) {
  const file = new URL(`${id}.jpg`, outDir);
  if (fs.existsSync(file) && !wanted.length) { console.log(`${id}: kept`); continue; }
  const pages = await search(queries[id]);
  let picked = null;
  for (const page of pages) {
    const info = page.imageinfo?.[0];
    if (!info || info.mime !== 'image/jpeg' || info.width < 800 || info.width < info.height * 1.1) continue;
    const meta = info.extmetadata ?? {};
    const license = strip(meta.LicenseShortName?.value);
    if (!okLicense.test(license)) continue;
    if (/diagram|logo|map of|flag of|svg|poster|book|cover/i.test(page.title)) continue;
    picked = { page, info, license, artist: strip(meta.Artist?.value) || 'Unknown', title: page.title.replace(/^File:/, '') };
    break;
  }
  if (!picked) { console.log(`${id}: NO MATCH for "${queries[id]}"`); continue; }
  const img = await fetch(picked.info.thumburl, { headers });
  fs.writeFileSync(file, Buffer.from(await img.arrayBuffer()));
  credits[id] = { file: `${id}.jpg`, title: picked.title, artist: picked.artist.slice(0, 120), license: picked.license, source: picked.info.descriptionurl };
  console.log(`${id}: ${picked.title} [${picked.license}]`);
  await new Promise(r => setTimeout(r, 400));
}

fs.writeFileSync(creditsFile, JSON.stringify(credits, null, 2));
const lines = ['# Quiz image credits', '', 'Images from Wikimedia Commons, resized to 800 px wide. Generated by scripts/fetch-quiz-images.mjs.', '', '| Question | Image | Author | License | Source |', '|---|---|---|---|---|'];
for (const id of Object.keys(credits).sort()) {
  const c = credits[id];
  lines.push(`| ${id} | ${c.title.replace(/\|/g, '/')} | ${c.artist.replace(/\|/g, '/')} | ${c.license} | [page](${c.source}) |`);
}
fs.writeFileSync(new URL('./CREDITS.md', outDir), lines.join('\n') + '\n');
